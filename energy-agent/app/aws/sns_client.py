"""
AWS Simple Notification Service (SNS) integration for high-priority grid alerts.

Safety Controls:
1. ONLY triggered for meaningful grid conditions (e.g. line congestion factor > 0.85 or feeder capacity headroom < 10%).
2. Cooldown deduplication logic prevents spamming notifications within 1 hour for the same zone.
3. Explicit opt-in subscriber model (no emails sent automatically).
4. Labelled explicitly as simulated microgrid notification.
"""

import os
import time
import json
import logging
from typing import Dict, Any, Optional
import boto3
from botocore.exceptions import ClientError

logger = logging.getLogger(__name__)

# In-memory cooldown cache: {f"{zone_code}:{alert_type}": last_sent_epoch}
_ALERT_COOLDOWN_CACHE: Dict[str, float] = {}
COOLDOWN_WINDOW_SECONDS = 3600  # 1 hour cooldown


def publish_grid_congestion_alert(
    zone_code: str,
    congestion_ratio: float,
    headroom_kwh: float,
    topic_arn: Optional[str] = None
) -> Dict[str, Any]:
    """
    Publishes an alert to an SNS Topic only if threshold is breached and cooldown has elapsed.
    """
    arn = topic_arn or os.getenv("GRID_ALERTS_TOPIC_ARN", "")
    cache_key = f"{zone_code}:CONGESTION"
    now = time.time()

    # Threshold condition: only alert if congestion > 0.85 OR headroom < 5.0 kWh
    if congestion_ratio < 0.85 and headroom_kwh > 5.0:
        return {
            "published": False,
            "reason": f"Condition normal (congestion {congestion_ratio:.2f}, headroom {headroom_kwh:.2f} kWh). No alert needed.",
            "is_simulation": True
        }

    # Cooldown deduplication:
    # 1. Fast in-memory check (for warm Lambda instances)
    last_sent = _ALERT_COOLDOWN_CACHE.get(cache_key, 0)
    if (now - last_sent) < COOLDOWN_WINDOW_SECONDS:
        remaining_sec = int(COOLDOWN_WINDOW_SECONDS - (now - last_sent))
        return {
            "published": False,
            "reason": f"Cooldown active for zone {zone_code} ({remaining_sec}s remaining). Alert suppressed.",
            "is_simulation": True
        }

    # 2. DynamoDB check (for cold Lambda instances across executions)
    try:
        from app.aws.dynamodb_client import query_recent_grid_events
        recent_alerts = query_recent_grid_events(event_type="SNS_CONGESTION_ALERT", limit=5)
        for evt in recent_alerts:
            if evt.get("zone_code") == zone_code:
                evt_time = evt.get("timestamp", "")
                if evt_time:
                    from datetime import datetime, timezone
                    clean_time = evt_time.split("#")[0]
                    parsed = datetime.fromisoformat(clean_time.replace("Z", "+00:00"))
                    diff = (datetime.now(timezone.utc) - parsed).total_seconds()
                    if diff < COOLDOWN_WINDOW_SECONDS:
                        return {
                            "published": False,
                            "reason": f"Persistent DynamoDB cooldown active for zone {zone_code} ({int(COOLDOWN_WINDOW_SECONDS - diff)}s remaining). Alert suppressed.",
                            "is_simulation": True
                        }
    except Exception as e:
        logger.debug(f"Persistent cooldown check bypassed: {e}")

    if not arn:
        return {
            "published": False,
            "reason": "SNS Topic ARN not configured. Alert suppressed.",
            "is_simulation": True
        }

    message_payload = {
        "event": "JANURJA_MICROGRID_ALERT",
        "zone": zone_code,
        "congestion_factor": round(congestion_ratio, 2),
        "available_headroom_kwh": round(headroom_kwh, 2),
        "timestamp": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "notice": "SIMULATION ONLY: Local microgrid feeder alert generated by JanUrja Grid Intelligence."
    }

    try:
        region = os.getenv("AWS_REGION", os.getenv("AWS_DEFAULT_REGION", "ap-south-1"))
        sns = boto3.client("sns", region_name=region)
        response = sns.publish(
            TopicArn=arn,
            Subject=f"[JanUrja Alert] Feeder Strain in {zone_code}",
            Message=json.dumps(message_payload, indent=2)
        )
        _ALERT_COOLDOWN_CACHE[cache_key] = now
        logger.info(f"Published SNS alert for {zone_code}: MessageId {response.get('MessageId')}")

        # Persist alert record in DynamoDB for cross-instance cooldown and audit trail
        try:
            from app.aws.dynamodb_client import persist_grid_event
            persist_grid_event(
                event_type="SNS_CONGESTION_ALERT",
                zone_code=zone_code,
                status="ALERT_SENT",
                metrics={"congestion_ratio": congestion_ratio, "headroom_kwh": headroom_kwh},
                summary=f"SNS alert dispatched to {arn} for line strain in {zone_code}"
            )
        except Exception as e:
            logger.debug(f"Alert event logging bypassed: {e}")

        return {
            "published": True,
            "message_id": response.get("MessageId"),
            "zone": zone_code,
            "is_simulation": True
        }
    except ClientError as e:
        logger.warning(f"SNS publish failed: {e.response['Error']['Code']}")
        return {"published": False, "reason": str(e), "is_simulation": True}
    except Exception as e:
        logger.warning(f"SNS error: {e}")
        return {"published": False, "reason": str(e), "is_simulation": True}
